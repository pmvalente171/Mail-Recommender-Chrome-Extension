// Runs after `npm run build` (the "postbuild" script). Writes build/config.js
// (backend URL, access key, study participant ID) from config.local.json,
// which is gitignored so the access key is never committed. Without that file,
// build/config.js keeps the development defaults copied from public/config.js
// (http://localhost:4000, no key, no participant).
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const localFile = path.join(root, 'config.local.json')
const outFile = path.join(root, 'build', 'config.js')

if (!fs.existsSync(localFile)) {
  console.log('config.local.json not found: the build uses the development backend (http://localhost:4000, no key).')
  process.exit(0)
}

let config
try {
  config = JSON.parse(fs.readFileSync(localFile, 'utf8'))
} catch (err) {
  console.error(`config.local.json is not valid JSON: ${err.message}`)
  process.exit(1)
}

const backendUrl = String(config.backendUrl || 'http://localhost:4000').replace(/\/+$/, '')
const apiKey = String(config.apiKey || '').trim()
const participant = String(config.participantId || '').trim()

const manifest = JSON.parse(fs.readFileSync(path.join(root, 'build', 'manifest.json'), 'utf8'))
const origin = new URL(backendUrl).origin
if (!manifest.host_permissions.includes(`${origin}/*`)) {
  console.error(`${origin}/* is missing from host_permissions in public/manifest.json; Chrome would block the calls.`)
  process.exit(1)
}
if (!apiKey && !/^http:\/\/localhost[:/]/.test(`${backendUrl}/`)) {
  console.warn(`Warning: no apiKey in config.local.json; ${backendUrl} will answer 401.`)
}

fs.writeFileSync(outFile, `// Generated by scripts/write-config.js from config.local.json. Do not commit.
export const BACKEND_URL = ${JSON.stringify(backendUrl)}
export const API_KEY = ${JSON.stringify(apiKey)}
export const PARTICIPANT = ${JSON.stringify(participant)}
`)
console.log(`build/config.js: ${backendUrl}, ${apiKey ? 'with an access key' : 'no access key'}, participant ${participant || '(none: nothing is stored for the study)'}.`)
